#!/usr/bin/env node
/**
 * Regenerate the contributors block in README.md from the GitHub API.
 *
 * Why a script and not an image service: README.md is static Markdown - GitHub
 * strips scripts, so nothing in it can fetch at render time. The usual
 * workaround is a third-party image (contrib.rocks and friends), but those call
 * the public API anonymously, so they return 404 for a private repository and
 * render as a broken image. This runs inside Actions with GITHUB_TOKEN, which
 * can read the repo whether it is private or public, and writes real Markdown.
 * Avatar URLs are public even when the repo is not, so the table renders for
 * anyone who can see the README.
 *
 * Rewrites only the region between the START/END markers, so hand-written prose
 * around it survives.
 *
 * Usage:
 *   node scripts/update-contributors.mjs
 *   GITHUB_REPOSITORY=owner/repo GITHUB_TOKEN=... node scripts/update-contributors.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const README = path.resolve(__dirname, '..', 'README.md');

const START = '<!-- CONTRIBUTORS:START - generated by scripts/update-contributors.mjs, do not edit by hand -->';
const END = '<!-- CONTRIBUTORS:END -->';

/** Avatars per row. Keeps the table readable on a phone as well as a desktop. */
const PER_ROW = 6;
const AVATAR_PX = 80;

const repo = process.env.GITHUB_REPOSITORY || 'NotGamerPratham/vpsgui';
const token = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '';

function api(pathname) {
  const headers = {
    Accept: 'application/vnd.github+json',
    'User-Agent': 'vpsgui-contributors-script',
    'X-GitHub-Api-Version': '2022-11-28',
  };
  // Unauthenticated works for a public repo; a private one needs the token that
  // Actions provides. Without it the API returns 404 rather than 403, so the
  // failure would otherwise look like "no such repo".
  if (token) headers.Authorization = `Bearer ${token}`;
  return fetch(`https://api.github.com${pathname}`, { headers });
}

/** Every contributor, following pagination. Bots are excluded. */
async function fetchContributors() {
  const all = [];
  for (let page = 1; page <= 10; page++) {
    const res = await api(`/repos/${repo}/contributors?per_page=100&page=${page}&anon=0`);

    if (res.status === 404) {
      throw new Error(
        `GitHub returned 404 for ${repo}. If the repository is private, this needs a token ` +
          `with read access (Actions passes GITHUB_TOKEN automatically).`
      );
    }
    if (res.status === 204) break; // Empty repository.
    if (!res.ok) {
      throw new Error(`GitHub API ${res.status} ${res.statusText} for ${repo}`);
    }

    const batch = await res.json();
    if (!Array.isArray(batch) || batch.length === 0) break;
    all.push(...batch);
    if (batch.length < 100) break;
  }

  return all
    .filter((c) => c && c.type !== 'Bot' && !String(c.login || '').endsWith('[bot]'))
    .sort((a, b) => (b.contributions || 0) - (a.contributions || 0));
}

/** An HTML table of avatars. HTML rather than Markdown so the images can be sized. */
function renderTable(contributors) {
  if (contributors.length === 0) {
    return '_No contributors reported by the GitHub API yet._';
  }

  const rows = [];
  for (let i = 0; i < contributors.length; i += PER_ROW) {
    const cells = contributors.slice(i, i + PER_ROW).map((c) => {
      const login = String(c.login);
      const count = c.contributions || 0;
      const plural = count === 1 ? 'commit' : 'commits';
      return (
        `      <td align="center">\n` +
        `        <a href="${c.html_url}">\n` +
        `          <img src="${c.avatar_url}&s=${AVATAR_PX * 2}" width="${AVATAR_PX}" height="${AVATAR_PX}" alt="${login}" style="border-radius:50%" /><br />\n` +
        `          <sub><b>${login}</b></sub>\n` +
        `        </a><br />\n` +
        `        <sub>${count} ${plural}</sub>\n` +
        `      </td>`
      );
    });
    rows.push(`    <tr>\n${cells.join('\n')}\n    </tr>`);
  }

  const total = contributors.reduce((sum, c) => sum + (c.contributions || 0), 0);
  const people = contributors.length === 1 ? 'contributor' : 'contributors';

  return (
    `<table>\n  <tbody>\n${rows.join('\n')}\n  </tbody>\n</table>\n\n` +
    `<sub><b>${contributors.length}</b> ${people} · <b>${total}</b> commits · ` +
    `updated automatically from the GitHub API</sub>`
  );
}

function spliceBlock(markdown, block) {
  const start = markdown.indexOf(START);
  const end = markdown.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `README.md is missing the contributor markers. Expected:\n${START}\n${END}`
    );
  }
  const before = markdown.slice(0, start + START.length);
  const after = markdown.slice(end);
  return `${before}\n\n${block}\n\n${after}`;
}

async function main() {
  const contributors = await fetchContributors();
  const markdown = await readFile(README, 'utf8');
  const updated = spliceBlock(markdown, renderTable(contributors));

  if (updated === markdown) {
    console.log(`Contributors unchanged (${contributors.length}).`);
    return;
  }

  await writeFile(README, updated, 'utf8');
  console.log(`Wrote ${contributors.length} contributor(s) into README.md.`);
}

// Exported for the unit test, which drives the pure rendering/splicing without
// touching the network.
export { main, renderTable, spliceBlock, START, END };

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('update-contributors.mjs')) {
  main().catch((err) => {
    console.error(`[contributors] ${err.message}`);
    process.exit(1);
  });
}
